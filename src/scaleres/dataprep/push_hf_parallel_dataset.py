def push_dataset(token: str) -> None:
    if not DATASET_DIR.exists():
        raise FileNotFoundError(
            f"Expected dataset directory {DATASET_DIR} is missing. Run the "
            "parallel dataset generation pipeline first."
        )

    dataset = load_from_disk(str(DATASET_DIR))
    dataset.push_to_hub(REPO_ID, token=token, private=False)
    print("Uploaded dataset splits to the Hugging Face Hub.")


def upload_readme(token: str) -> None:
    api = HfApi()
    api.upload_file(
        path_or_fileobj=io.BytesIO(MODEL_CARD.encode("utf-8")),
        path_in_repo="README.md",
        repo_id=REPO_ID,
        repo_type="dataset",
        token=token,
    )
    print("Uploaded README metadata to the Hub.")


def main() -> None:
    parser = argparse.ArgumentParser(
        description=(
            "Push the dataset splits and/or README for the Indonesian–Balinese–"
            "Cirebonese synthetic corpus."
        )
    )
    parser.add_argument(
        "--readme-only",
        action="store_true",
        help=(
            "Upload just the README/model card without re-uploading the dataset"
            " artifacts."
        ),
    )
    args = parser.parse_args()

    token = os.environ.get("HF_TOKEN")
    if not token:
        raise EnvironmentError(
            "Set the HF_TOKEN environment variable with write access to the "
            "haznitrama organization before running this script."
        )

    if not args.readme_only:
        push_dataset(token)

    upload_readme(token)

    print(
        f"All requested uploads complete. View the dataset at "
        f"https://huggingface.co/datasets/{REPO_ID}"
    )


if __name__ == "__main__":
    main()
